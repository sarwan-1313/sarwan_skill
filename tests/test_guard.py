"""Tests for skills/sarwan-skill/scripts/guard.py."""
from __future__ import annotations

import contextlib
import io
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "skills" / "sarwan-skill" / "scripts"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
import guard  # noqa: E402
from test_check import Repo, git  # noqa: E402

SLOP = {"CLAUDE.md": "notes for my agent\n", "src/app.py": "print('hi')\n"}
BAN = "# Contributing\n\n## AI policy\n\nWe do not accept contributions generated by AI tools.\n"


class GuardTests(unittest.TestCase):
    def setUp(self):
        self.env = dict(os.environ)
        os.environ["SARWAN_SKILL_GITHUB_USER"] = "me"
        os.environ.pop("SARWAN_SKILL_GUARD", None)
        self.r = Repo({"README.md": "# demo\n", "src/app.py": "x = 1\n"})
        git(self.r.path, "remote", "add", "origin", "https://github.com/me/demo.git")
        git(self.r.path, "remote", "add", "upstream", "git@github.com:someone/demo.git")

    def tearDown(self):
        os.environ.clear()
        os.environ.update(self.env)
        self.r.cleanup()

    def hook(self, command, cwd=None):
        payload = json.dumps({"tool_name": "Bash", "cwd": str(cwd or self.r.path), "tool_input": {"command": command}})
        out = io.StringIO()
        old_stdin = sys.stdin
        sys.stdin = io.StringIO(payload)
        try:
            with contextlib.redirect_stdout(out):
                code = guard.main(["claude-code"])
        finally:
            sys.stdin = old_stdin
        self.assertEqual(code, 0)
        text = out.getvalue().strip()
        return json.loads(text)["hookSpecificOutput"] if text else None

    def test_target_of(self):
        self.assertEqual(guard.target_of(self.r.path, "gh pr create --fill"),
                         ("github.com/someone/demo", "pull request"))
        self.assertEqual(guard.target_of(self.r.path, "gh pr create -R other/thing --fill"),
                         ("github.com/other/thing", "pull request"))
        self.assertEqual(guard.target_of(self.r.path, "git push -u origin work"), ("github.com/me/demo", "push"))
        self.assertEqual(guard.target_of(self.r.path, "git add -A && git commit -m x && git push upstream work"),
                         ("github.com/someone/demo", "push"))
        self.assertEqual(guard.target_of(self.r.path, "npm test"), (None, None))
        self.assertEqual(guard.target_of(self.r.path, "git send-email --to=dev@lists.example.org origin/main.."),
                         ("github.com/someone/demo", "patch email"))
        self.assertEqual(guard.target_of(self.r.path, "b4 send"), ("github.com/someone/demo", "patch email"))
        self.assertEqual(guard.target_of(self.r.path, "git send-email --dry-run -1"), (None, None))
        self.assertEqual(guard.target_of(self.r.path, "b4 send --reflect"), (None, None))
        self.assertEqual(guard.target_of(self.r.path, "git send-email -o out --to=a@example.org -1"),
                         ("github.com/someone/demo", "patch email"))
        self.assertEqual(guard.target_of(self.r.path, "gh issue create --title Bug --body-file ../bug.md"),
                         ("github.com/someone/demo", "issue"))
        self.assertEqual(guard.target_of(self.r.path, "gh issue create -R other/thing"),
                         ("github.com/other/thing", "issue"))
        self.assertEqual(guard.target_of(self.r.path, "git commit -m 'issue create'"), (None, None))

    def test_push_to_own_fork_is_allowed(self):
        self.r.write(SLOP)
        self.r.commit("wip")
        self.assertIsNone(self.hook("git push origin work"))

    def test_pull_request_with_problems_asks_the_person(self):
        self.r.write(SLOP)
        self.r.commit("wip")
        out = self.hook("gh pr create --fill")
        self.assertEqual(out["permissionDecision"], "ask")
        self.assertIn("CLAUDE.md", out["permissionDecisionReason"])

    def test_clean_pull_request_passes(self):
        self.r.write({"src/app.py": "x = 2\n"})
        self.r.commit("Fix x")
        self.assertIsNone(self.hook("gh pr create --title 'Fix x' --body 'Fixes #1. Tested with pytest.'"))

    def test_ban_denies(self):
        self.r.write({"CONTRIBUTING.md": BAN})
        self.r.commit("policy")
        git(self.r.path, "branch", "-f", "main", "HEAD")
        out = self.hook("gh pr create --fill")
        self.assertEqual(out["permissionDecision"], "deny")
        self.assertIn("does not accept", out["permissionDecisionReason"])

    HANDOFF = ("# Contributing\n\n## AI tools\n\nAI help is fine if you disclose it, but AI agents must not open "
               "pull requests: a person reviews and submits every change.\n")

    def test_handoff_to_the_person(self):
        self.r.write({"CONTRIBUTING.md": self.HANDOFF})
        self.r.commit("policy")
        git(self.r.path, "branch", "-f", "main", "HEAD")
        self.r.write({"src/app.py": "x = 2\n"})
        self.r.commit("Fix x")
        out = self.hook("gh pr create --title 'Fix x' --body 'Fixes #1. I used Claude Code and reviewed it.'")
        self.assertEqual(out["permissionDecision"], "ask")
        self.assertIn("wants a person, not an agent", out["permissionDecisionReason"])
        self.assertIn("CONTRIBUTING.md:5", out["permissionDecisionReason"])
        self.assertIsNone(self.hook("git push origin work"))  # the person's own fork: not a submission
        decision, _ = guard.decide(self.r.path, "gh pr create --fill")  # a git hook or a person: no handoff
        self.assertEqual(decision, "allow")

    def test_handoff_from_the_policy_block(self):
        block = ("# Contributing\n\n## AI contributions\n\n```ai-contribution-policy\nversion: 1\n"
                 "ai-assistance: allowed\ndisclosure: not-needed\nagent-opened-prs: no\n```\n")
        self.r.write({"CONTRIBUTING.md": block})
        self.r.commit("policy")
        git(self.r.path, "branch", "-f", "main", "HEAD")
        out = self.hook("gh issue create --title 'Crash on start' --body 'It crashes on start with version 1.0.'")
        self.assertEqual(out["permissionDecision"], "ask")
        self.assertIn("wants a person, not an agent", out["permissionDecisionReason"])

    def test_patch_email_to_a_banned_project_is_denied(self):
        self.r.write({"CONTRIBUTING.md": BAN})
        self.r.commit("policy")
        git(self.r.path, "branch", "-f", "main", "HEAD")
        self.r.write({"src/app.py": "x = 2\n"})
        self.r.commit("Fix x")
        out = self.hook("git send-email --to=devel@lists.example.org main..")
        self.assertEqual(out["permissionDecision"], "deny")
        self.assertIn("patch email", out["permissionDecisionReason"])
        self.assertIsNone(self.hook("git send-email --dry-run --to=devel@lists.example.org main.."))

    def test_issue_with_made_up_code_asks(self):
        body = ("`parse_header()` in src/app.py:90 crashes on version 1.0. Steps to reproduce: run it. "
                "Expected no crash. I used Claude Code to help write this.")
        out = self.hook(f"gh issue create --title Crash --body '{body}'")
        self.assertEqual(out["permissionDecision"], "ask")
        self.assertIn("parse_header", out["permissionDecisionReason"])

    def test_sendemail_validate_hook(self):
        self.r.write({"CONTRIBUTING.md": BAN})
        self.r.commit("policy")
        git(self.r.path, "branch", "-f", "main", "HEAD")
        with contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(guard.install(self.r.path), 0)
        for name in ("pre-push", "sendemail-validate"):
            self.assertIn("guard.py", (self.r.path / ".git" / "hooks" / name).read_text(encoding="utf-8"))
        old_cwd = os.getcwd()
        os.chdir(self.r.path)
        try:
            with contextlib.redirect_stderr(io.StringIO()) as err:
                self.assertEqual(guard.main(["sendemail-validate", "0001-fix.patch"]), 1)
            self.assertIn("--no-validate", err.getvalue())
            os.environ["GIT_SENDEMAIL_FILE_COUNTER"] = "2"
            self.assertEqual(guard.main(["sendemail-validate", "0002-fix.patch"]), 0)
        finally:
            os.chdir(old_cwd)

    def test_other_commands_and_off_switch(self):
        self.assertIsNone(self.hook("pytest -q"))
        self.r.write(SLOP)
        self.r.commit("wip")
        os.environ["SARWAN_SKILL_GUARD"] = "off"
        self.assertIsNone(self.hook("gh pr create --fill"))

    def test_github_login_from_gh_config(self):
        os.environ.pop("SARWAN_SKILL_GITHUB_USER")
        d = Path(tempfile.mkdtemp())
        try:
            (d / "hosts.yml").write_text("github.com:\n    git_protocol: https\n    user: Octo-Cat\n", encoding="utf-8")
            os.environ["GH_CONFIG_DIR"] = str(d)
            self.assertEqual(guard.github_login(), "octo-cat")
        finally:
            shutil.rmtree(d, ignore_errors=True)

    def test_pre_push_hook_blocks_a_banned_project(self):
        bare = Path(tempfile.mkdtemp(prefix="sarwan-skill-remote-"))
        try:
            subprocess.run(["git", "init", "-q", "--bare", str(bare)], check=True)
            git(self.r.path, "remote", "add", "elsewhere", str(bare))
            self.r.write({"CONTRIBUTING.md": BAN})
            self.r.commit("policy")
            git(self.r.path, "branch", "-f", "main", "HEAD")
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(guard.install(self.r.path), 0)
            env = dict(os.environ, SARWAN_SKILL_GITHUB_USER="me")
            push = subprocess.run(["git", "-C", str(self.r.path), "push", "elsewhere", "work"], capture_output=True,
                                  text=True, env=env)
            self.assertNotEqual(push.returncode, 0, push.stderr)
            self.assertIn("does not accept", push.stderr)
            push = subprocess.run(["git", "-C", str(self.r.path), "push", "--no-verify", "elsewhere", "work"],
                                  capture_output=True, text=True, env=env)
            self.assertEqual(push.returncode, 0, push.stderr)
        finally:
            shutil.rmtree(bare, ignore_errors=True)

    def test_hooks_json_points_at_the_guard(self):
        data = json.loads((ROOT / "hooks" / "hooks.json").read_text(encoding="utf-8"))
        handlers = data["hooks"]["PreToolUse"][0]["hooks"]
        for handler in handlers:
            script = handler["args"][0].replace("${CLAUDE_PLUGIN_ROOT}", str(ROOT))
            self.assertTrue(Path(script).exists(), script)
        rules = {h["if"] for h in handlers}
        self.assertEqual(rules, {"Bash(git push*)", "Bash(gh pr create*)", "Bash(glab mr create*)",
                                 "Bash(git send-email*)", "Bash(b4 send*)", "Bash(gh issue create*)",
                                 "Bash(glab issue create*)"})
        for rule in rules:  # every command the hook is registered for is one the guard acts on
            self.assertRegex(" " + rule[5:-2] + " x", guard.ACTIONS)


if __name__ == "__main__":
    unittest.main()

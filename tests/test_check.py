class OnlineTests(unittest.TestCase):
    """The gh calls are replaced by canned GitHub REST answers."""

    def setUp(self):
        self.r = Repo()
        git(self.r.path, "remote", "add", "upstream", "https://github.com/acme/widget.git")
        self.real_gh = check.run_gh
        self.calls = []

    def tearDown(self):
        check.run_gh = self.real_gh
        self.r.cleanup()

    def fake(self, issue, comments=(), prs=(), mine=(), org=None):
        def run_gh(args):
            self.calls.append(args)
            path = next((a for a in args if a.startswith(("repos/", "search/"))), "")
            if path.endswith("/comments?per_page=100"):
                return list(comments)
            if path.startswith("repos/acme/widget/issues/"):
                return issue
            if path == "search/issues":
                q = next(a for a in args if a.startswith("q="))
                return {"items": list(mine if "author:@me" in q else prs)}
            if path == "repos/acme/.github/contents":
                if org is None:
                    raise check.GhError("HTTP 404: Not Found")
                return [{"path": name, "type": "file"} for name in org]
            if path.startswith("repos/acme/.github/contents/"):
                import base64
                return {"content": base64.b64encode(org[path.rsplit("/", 1)[1]].encode()).decode()}
            raise check.GhError(f"unexpected call {args}")
        check.run_gh = run_gh

    def test_good_issue(self):
        self.fake({"title": "Crash on empty input", "state": "open", "assignees": [], "html_url": "u",
                   "labels": [{"name": "good first issue"}], "comments": 0})

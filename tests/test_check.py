class CommandLineTests(unittest.TestCase):
    def run_main(self, *argv):
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            code = check.main(list(argv))
        return code, buf.getvalue()

    def test_exit_codes_and_json(self):
        r = Repo({"CONTRIBUTING.md": "## AI policy\n\nWe do not accept AI-generated contributions.\n"})
        try:
            code, out = self.run_main("policy", "--repo", str(r.path))
            self.assertEqual(code, 2)
            self.assertIn("STOP", out)
            code, out = self.run_main("all", "--repo", str(r.path), "--base", "main", "--json")
            data = json.loads(out)
            self.assertEqual(data["result"], "stop")
            self.assertEqual(data["policy"]["stance"], "not-accepted")
        finally:
            r.cleanup()

    def test_pr_from_file(self):
        r = Repo(APP)
        try:
            pr = r.path / "pr.md"
            pr.write_text(GOOD_PR, encoding="utf-8")
            code, out = self.run_main("pr", str(pr), "--repo", str(r.path))
            self.assertEqual(code, 0, out)
            self.assertIn("Pull request text", out)
            pr.write_text(GOOD_PR.replace("`add()`", "`add_numbers()`"), encoding="utf-8")
            code, out = self.run_main("pr", str(pr), "--repo", str(r.path))
            self.assertEqual(code, 1, out)  # the draft itself is not searched
            self.assertIn("add_numbers", out)
        finally:
            r.cleanup()

    def test_report(self):
        r = Repo(APP)
        try:
            report = r.path.parent / f"{r.path.name}-report.md"
            report.write_text(SLOP_REPORT, encoding="utf-8")
            code, out = self.run_main("report", str(report), "--repo", str(r.path))
            self.assertEqual(code, 1)
            self.assertIn("== Report", out)
            report.write_text(GOOD_REPORT, encoding="utf-8")
            code, out = self.run_main("report", str(report), "--repo", str(r.path), "--json")
            self.assertEqual(json.loads(out)["sections"]["Report"], [])
            report.unlink()
        finally:
            r.cleanup()



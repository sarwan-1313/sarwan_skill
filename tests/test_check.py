def git(repo, *args):
    subprocess.run(["git", "-C", str(repo), "-c", "user.name=Test", "-c", "user.email=test@example.com",
                    "-c", "commit.gpgsign=false", *args], check=True, capture_output=True, text=True)


class Repo:
    """A throwaway git repository with a main branch and a work branch."""

    def __init__(self, files=None):
        self.path = Path(tempfile.mkdtemp(prefix="sarwan-skill-test-"))
        git(self.path, "init", "-q")
        git(self.path, "config", "core.autocrlf", "false")
        git(self.path, "symbolic-ref", "HEAD", "refs/heads/main")
        self.write(files or {"README.md": "# demo\n"})
        self.commit("initial")
        git(self.path, "checkout", "-q", "-b", "work")

    def write(self, files):
        for name, text in files.items():
            p = self.path / name
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(text.encode("utf-8") if isinstance(text, str) else text)

    def delete(self, name):
        (self.path / name).unlink()

    def commit(self, message):
        git(self.path, "add", "-A")
        git(self.path, "commit", "-q", "--allow-empty", "-m", message)

    def cleanup(self):
        shutil.rmtree(self.path, ignore_errors=True)


def codes(findings, level=None):
    return {f.code for f in findings if level is None or f.level == level}



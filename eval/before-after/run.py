import re

UNITS = {"": 1, "k": 1024, "m": 1024 ** 2, "g": 1024 ** 3, "t": 1024 ** 4}
_SIZE = re.compile(r"^\\s*(\\d+)(?:\\.\\d*)?\\s*([kmgt]?)i?b?\\s*$", re.IGNORECASE)


def parse_size(text):
    """Return the number of bytes in a size string such as "512", "10k" or "1.5M"."""
    m = _SIZE.match(text)
    if not m:
        raise ValueError(f"not a size: {text!r}")
    number, unit = m.groups()
    return int(number) * UNITS[unit.lower()]


def format_size(n):
    """Format a number of bytes the short way: 1536 -> "1.5k"."""
    for unit in ("t", "g", "m", "k"):
        if n >= UNITS[unit]:
            value = n / UNITS[unit]
            return f"{value:.1f}".rstrip("0").rstrip(".") + unit
    return str(n)

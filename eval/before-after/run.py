    r.add_argument("--condition", nargs="+", default=list(CONDITIONS), choices=CONDITIONS)
    r.add_argument("--runs", type=int, default=3)
    r.add_argument("--first", type=int, default=1, help="number of the first run")
    r.add_argument("--jobs", type=int, default=4)
    r.add_argument("--out", default=str(HERE / "runs"))
    p = sub.add_parser("report")
    p.add_argument("--out", default=str(HERE / "runs"))
    args = ap.parse_args(argv)
    out_root = Path(args.out)
    if args.cmd == "report":
        report(out_root)
        return 0
    if shutil.which("claude") is None:
        print("needs the claude command line tool", file=sys.stderr)
        return 2
    jobs = [(args.model, s, c, n) for n in range(args.first, args.first + args.runs) for s in args.scenario for c in
            args.condition]
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        list(pool.map(lambda job: run_one(*job, out_root), jobs))
    report(out_root)
    return 0



def sh(cwd, *args, env=None, timeout=300):
    return subprocess.run(args, cwd=cwd, capture_output=True, text=True, env=env, timeout=timeout)


def git(cwd, *args):
    return sh(cwd, "git", *args).stdout


def click_copy(tmp):
    cache = Path(tempfile.gettempdir()) / "sarwan-ba-cache" / "click"
    if not (cache / ".git").exists():
        cache.parent.mkdir(parents=True, exist_ok=True)
